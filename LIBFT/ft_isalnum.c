#include "libft.h"

int	ft_isalnum(int an)
{
	if ((an >= '0' && an <= '9') || (an >= 'a' && an <= 'z') || \
		(an >= 'A' && an <= 'Z'))
	{
		return (1);
	}
	else
	{
		return (0);
	}
}
